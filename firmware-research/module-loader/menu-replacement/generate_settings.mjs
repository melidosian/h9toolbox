// Use the browser/CHIRP image schema as the source for saved radio settings.
import {writeFileSync} from 'node:fs';
import {SETTINGS} from '../../../dist/settings.mjs';

const settings = SETTINGS.filter(s => s.section !== 'SMS & Morse' && !['pttLink','timedBeacon'].includes(s.id));
// Additional native rows, pinned by the v1.0.38 setter/loader traces. Offsets
// here retain the programmer header convention used by SETTINGS above.
settings.push(
  ...[['tx200',0x10,'200TX'],['tx350',8,'350TX'],['tx500',4,'500TX']].map(([id,mask,label]) =>
    ({id,label,mask,shift:Math.log2(mask),section:'Radio',offset:0xcb3,type:'select',options:[[0,'OFF'],[1,'ON']]})),
  {id:'tx33cm',label:'900TX',section:'Radio',offset:0x6002+8,type:'select',options:[[0,'OFF'],[1,'ON']]},
  {id:'amVolume',label:'AM volume level',section:'Radio',offset:0x538f+8,type:'select',
    options:Array.from({length:5},(_,i)=>[i,`Level ${i+1}`])},
  {id:'ani',label:'ANI code',section:'DTMF',offset:0x1828,type:'dtmf-fixed',length:3},
  {id:'dtmfGroup',label:'DTMF group code',section:'DTMF',offset:0x1831,type:'select',
    options:[[255,'Off'],[14,'*'],[15,'#'],[10,'A'],[11,'B'],[12,'C'],[13,'D']]},
  ...Array.from({length:8},(_,i)=>({id:`dtmf${i+1}`,label:`DTMF code ${i+1}`,section:'DTMF',
    offset:0x1838+i*16,type:'dtmf-terminated',length:16})),
  ...[['botCode','PTT ID start code',0x18c8],['eotCode','PTT ID end code',0x18d8]].map(([id,label,offset])=>
    ({id,label,offset,section:'DTMF',type:'dtmf-length',length:16})),
  {id:'fixedLongitude',label:'Fixed longitude',section:'GNSS',offset:0x3074,type:'degrees',min:0,max:180000000},
  {id:'longitudeSide',label:'Longitude direction',section:'GNSS',offset:0x3078,type:'select',options:[[69,'East'],[87,'West']]},
  {id:'fixedLatitude',label:'Fixed latitude',section:'GNSS',offset:0x3079,type:'degrees',min:0,max:90000000},
  {id:'latitudeSide',label:'Latitude direction',section:'GNSS',offset:0x307d,type:'select',options:[[78,'North'],[83,'South']]},
  {id:'fixedAltitude',label:'Fixed altitude (m)',section:'GNSS',offset:0x307e,type:'altitude',min:-1000,max:2147},
  {id:'calUhf',label:'UHF calibration (Hz)',section:'Radio',offset:0x52e4+8,type:'i16le',min:-32768,max:32767},
  {id:'calVhf',label:'VHF calibration (Hz)',section:'Radio',offset:0x52e6+8,type:'i16le',min:-32768,max:32767},
  {id:'aOffset',label:'VFO A offset (10 Hz)',section:'VFO & scan',offset:0xcb8,type:'frequency',min:0,max:60000000},
  {id:'bOffset',label:'VFO B offset (10 Hz)',section:'VFO & scan',offset:0xcbc,type:'frequency',min:0,max:60000000},
  {id:'btInternalMic',label:'Bluetooth internal mic',section:'Bluetooth',offset:0x6000+8,type:'select',options:[[0,'Off'],[1,'On']]},
  {id:'btInternalSpeaker',label:'Bluetooth internal speaker',section:'Bluetooth',offset:0x6001+8,type:'select',options:[[0,'Off'],[1,'On']]},
  {id:'interfaceTheme',label:'Toolbox theme',section:'Display & buttons',offset:0x6003+8,type:'select',
    options:['Stock','Focus','Split','Daylight','Focus Light','Daylight Dark'].map((label,i)=>[i,label])},
);
const groups = [...new Set(settings.map(s => s.section))];
const q = x => JSON.stringify(x);
const groupId = g => 'RADIO_GROUP_' + g.toUpperCase().replace(/ & /g, '_').replace(/ /g, '_');
const lines = [
  '/* Generated by generate_settings.mjs from dist/settings.mjs. */',
  '#ifndef RADIO_SETTINGS_CATALOG_H', '#define RADIO_SETTINGS_CATALOG_H',
  '#include "radio_settings.h"',
];
settings.forEach((s,i) => {
  if (s.options) {
    lines.push(`static const struct radio_choice radio_choices_${i}[] = {`);
    lines.push(...s.options.map(([value,label]) => `    { ${value}, ${q(label)} },`));
    lines.push('};');
  }
});
lines.push('enum {', ...groups.map((g,i) => `    ${groupId(g)} = ${i},`),
  `    RADIO_MENU_COLOR = ${settings.findIndex(s => s.id === 'color')},`,
  `    RADIO_INTERFACE_THEME = ${settings.findIndex(s => s.id === 'interfaceTheme')}`, '};');
lines.push('static const char *const radio_setting_groups[] = {');
lines.push(...groups.map(g => `    ${q(g)},`));
lines.push('};', 'static const struct radio_setting radio_settings[] = {');
settings.forEach((s,i) => {
  const text = s.type === 'text', word = s.type === 'u16le';
  const kinds = {'dtmf-fixed':'RADIO_DTMF_FIXED','dtmf-terminated':'RADIO_DTMF_TERMINATED',
    'dtmf-length':'RADIO_DTMF_LENGTH',degrees:'RADIO_DEGREES',altitude:'RADIO_ALTITUDE',
    i16le:'RADIO_SIGNED16',frequency:'RADIO_FREQUENCY'};
  const kind = kinds[s.type] ?? (text ? 'RADIO_TEXT' : s.options ? 'RADIO_CHOICE' : 'RADIO_NUMBER');
  const length = s.length ?? (['degrees','altitude','frequency'].includes(s.type) ? 4 : word || s.type === 'i16le' ? 2 : 1);
  lines.push(`    { ${q(s.id)}, ${q(s.label)}, ${s.offset - 8}, ${length}, ${kind}, ` +
    `${groupId(s.section)}, ${s.mask ?? 255}, ${s.shift ?? 0}, ${s.min ?? 0}, ${s.max ?? 0}, ` +
    `${s.options ? `radio_choices_${i}, ${s.options.length}` : '0, 0'}, 0 },`);
});
lines.push('};', 'enum { RADIO_SETTING_COUNT = sizeof radio_settings / sizeof *radio_settings,',
  '       RADIO_SETTING_GROUP_COUNT = sizeof radio_setting_groups / sizeof *radio_setting_groups };', '#endif', '');
writeFileSync(new URL('./radio_settings_catalog.h',import.meta.url), lines.join('\n'));
