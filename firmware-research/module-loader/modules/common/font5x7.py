def parse() -> dict[str, list[int]]:
    glyphs: dict[str, list[int]] = {}
    lines = [l for l in ART.splitlines() if l.strip()]
    for i in range(0, len(lines), 8):
        name, rows = lines[i], lines[i + 1:i + 8]
        if not (len(name) == 3 and name[0] == name[2] == "'") or len(rows) != 7:
            raise ValueError(f"bad glyph block at line {i}: {name!r}")
        if any(len(r) != 5 or set(r) - {".", "#"} for r in rows):
            raise ValueError(f"bad rows for {name}")
        glyphs[name[1]] = [int(r.replace(".", "0").replace("#", "1"), 2) for r in rows]
    return glyphs


def main() -> None:
    glyphs = parse()
    chars = "".join(glyphs)
    out = ["/* Generated by font5x7.py; do not edit. 5x7 glyphs, one byte per row,",
           " * bit 4 = left column. FONT_CHARS[i] is drawn with FONT[i]. */",
           f"static const char FONT_CHARS[] = {chars!r};".replace("'", '"'),
           f"static const uint8_t FONT[{len(chars)}][7] = {{"]
    for c, rows in glyphs.items():
        out.append(f"    {{{', '.join(f'0x{r:02x}' for r in rows)}}}, /* {c} */")
    out.append("};")
    Path(__file__).with_name("font.h").write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
