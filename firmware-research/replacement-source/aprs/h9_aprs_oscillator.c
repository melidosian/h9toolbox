void h9_aprs_oscillator_init(H9AprsOscillator *oscillator)
{
    if (oscillator == NULL) return;
    oscillator->phase = 0;
    oscillator->step = 0x40u;
}

bool h9_aprs_oscillator_set_step(H9AprsOscillator *oscillator, uint16_t step)
{
    if (oscillator == NULL || (step != 0x40u && step != 0x75u)) return false;
    oscillator->step = step;
    return true;
}

uint8_t h9_aprs_oscillator_next(H9AprsOscillator *oscillator)
{
    uint8_t within_half;
    uint8_t index;
    uint8_t sample;
    if (oscillator == NULL) return 0;
    oscillator->phase = (uint16_t)((oscillator->phase + oscillator->step) & 0x1FFu);
    within_half = (uint8_t)oscillator->phase;
    index = within_half > 0x7Fu ? (uint8_t)(0xFFu - within_half) : within_half;
    sample = quarter_wave[index];
    return oscillator->phase > 0xFFu ? (uint8_t)(0xFFu - sample) : sample;
}
