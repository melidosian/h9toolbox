#ifndef H9_APRS_DEMOD_H
#define H9_APRS_DEMOD_H

#include "h9_aprs_bitstream.h"
#include "h9_aprs_ring.h"
#include <stdbool.h>
#include <stdint.h>

/* Reconstructed from APRS image 0x08002604 and 0x08002308.
   The caller supplies the signed sample generated by ADC callback 0x08002EF8.
   Output is the byte stream produced at 0x080055C4, including 0x7E flags. */
typedef struct {
    uint8_t delay_bytes[5];
    uint8_t receive_bytes[64];
    H9AprsRing delay;
    H9AprsRing receive;
    H9AprsBitstream bitstream;
    int16_t correlation_previous;
    int16_t correlation_current;
    int16_t filter_previous;
    int16_t filter_current;
    uint8_t symbol_history;
    uint8_t bit_history;
    uint8_t no_transition_count;
    /* ISR-only writer; main loop observes a monotonic generation. */
    _Atomic uint32_t queue_overflow;
    /* Bit 0: in frame; bit 1: six-flag preamble. Published by ADC ISR. */
    _Atomic uint32_t gate_flags;
    int16_t timing;
} H9AprsDemod;

void h9_aprs_demod_init(H9AprsDemod *demod);
bool h9_aprs_demod_sample(H9AprsDemod *demod, int16_t normalized_sample);
bool h9_aprs_demod_pop_byte(H9AprsDemod *demod, uint8_t *byte);
typedef struct {
    bool in_frame;
    bool preamble_seen;
    uint32_t queue_overflow;
} H9AprsDemodGateState;
H9AprsDemodGateState h9_aprs_demod_gate_state(const H9AprsDemod *demod);

#endif
